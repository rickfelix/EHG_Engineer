-- DEFECT (measured 2026-08-19 vs main 578ea816f4c): lib/npm-install-lock.cjs acquireLock() is check-then-insert
-- (findActiveLock SELECT, then unconditional INSERT of message_type='INFO', subject='NODE_MODULES_LOCK',
-- payload.lock_type='NODE_MODULES', payload.status='locked'). Two concurrent acquirers both pass the SELECT and
-- both insert: NODE_MODULES_LOCK "fires perfectly and provides no mutual exclusion". No unique constraint exists.
-- FIX (this half): a PARTIAL UNIQUE INDEX so at most ONE live lock row can exist; the second INSERT fails with
-- 23505 and the caller's existing error path treats it as "held". The lint half (identifier-claims-what-it-prevents)
-- ships separately as the QF's code change.
-- Release today = read_at stamp (lib/npm-install-lock.cjs L66/L114/L148) — the index predicate therefore keys on
-- read_at IS NULL so a released (read) lock row frees the slot. Stale-lock auto-expire also stamps read_at.
-- PRECONDITION: at most one live lock row may exist at apply time, else CREATE UNIQUE INDEX fails (that is the
-- honest outcome — it means two holders exist right now; resolve first).
-- Rollback: DROP INDEX IF EXISTS public.session_coordination_node_modules_lock_one_live;
-- Idempotent: IF NOT EXISTS.

BEGIN;

CREATE UNIQUE INDEX IF NOT EXISTS session_coordination_node_modules_lock_one_live
  ON public.session_coordination ((payload->>'lock_type'))
  WHERE message_type = 'INFO'
    AND subject = 'NODE_MODULES_LOCK'
    AND payload->>'lock_type' = 'NODE_MODULES'
    AND payload->>'status' = 'locked'
    AND read_at IS NULL;

-- POSTCONDITION
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_indexes WHERE schemaname='public' AND indexname='session_coordination_node_modules_lock_one_live') THEN
    RAISE EXCEPTION 'POSTCONDITION FAILED: lock index missing';
  END IF;
END $$;

COMMIT;
