#!/usr/bin/env node
// SD-LEO-INFRA-RETRO-PROMOTION-PATH-001 FR-4 (TS-6): generates a COMMITTED SNAPSHOT of real
// retro_type=HANDOFF rows classified by the corrected classifyRetro(), for a DB-free replay test
// (tests/unit/retro-clobber-handoff-replay.test.js). A committed snapshot, not a live query
// inside the test, keeps the test out of this repo's DB-test guard and matches this session's
// established pattern (see the immediately-prior SD, SD-LEO-INFRA-FORECASTER-CLAIMABLE-
// PREDICATE-001, for the same technique applied to belt_capacity_verdicts).
//
// Only generated_by/key_learnings/retro_type/status/quality_score are persisted -- the fields
// classifyRetro() actually reads. No titles, descriptions, SD keys, or session ids are included.
import 'dotenv/config';
import { createClient } from '@supabase/supabase-js';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { classifyRetro } from '../modules/handoff/lib/retro-clobber-guard.js';
import { isMainModule } from '../../lib/utils/is-main-module.js';

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT_PATH = resolve(__dirname, '../../tests/fixtures/retro-handoff-classification-snapshot.json');
const SAMPLE_SIZE = 150;

export async function generateSnapshot() {
  const supabase = createClient(
    process.env.SUPABASE_URL || process.env.NEXT_PUBLIC_SUPABASE_URL,
    process.env.SUPABASE_SERVICE_ROLE_KEY
  );

  const { data, error, count } = await supabase
    .from('retrospectives')
    .select('generated_by, key_learnings, retro_type, status, quality_score', { count: 'exact' })
    .eq('retro_type', 'HANDOFF')
    .order('created_at', { ascending: false })
    .limit(SAMPLE_SIZE);
  if (error) throw new Error(`fetch failed: ${error.message}`);

  const rows = data.map((r) => ({
    row: {
      generated_by: r.generated_by,
      key_learnings: r.key_learnings,
      retro_type: r.retro_type,
      status: r.status,
      quality_score: r.quality_score,
    },
    expected: classifyRetro(r),
  }));

  const tally = {};
  for (const r of rows) tally[r.expected.reason] = (tally[r.expected.reason] || 0) + 1;
  const autoGeneratedRefused = rows.filter(
    (r) => r.row.generated_by && !r.expected.safe && r.expected.reason === 'rich_existing_content'
  ).length;

  const out = {
    _comment: `SD-LEO-INFRA-RETRO-PROMOTION-PATH-001 FR-4 (TS-6): committed snapshot of ${rows.length} real retro_type=HANDOFF rows (of ${count} total live), each paired with its EXPECTED classifyRetro() output under the CORRECTED (post-fix) logic. Pulled 2026-08-24. The replay test asserts the live classifyRetro() import matches every 'expected' value, AND that zero auto-generated rows refuse via rich_existing_content (the defect this SD fixes).`,
    live_total_handoff_count: count,
    sample_size: rows.length,
    reason_tally: tally,
    auto_generated_refused_count: autoGeneratedRefused,
    rows,
  };

  writeFileSync(OUT_PATH, JSON.stringify(out, null, 2) + '\n');
  console.log(`Wrote ${rows.length} rows to ${OUT_PATH}`);
  console.log('Reason tally:', JSON.stringify(tally));
  console.log('Auto-generated rows still refusing (should be 0 post-fix):', autoGeneratedRefused);
  return out;
}

if (isMainModule(import.meta.url)) {
  generateSnapshot().catch((err) => {
    console.error(err);
    process.exit(1);
  });
}
