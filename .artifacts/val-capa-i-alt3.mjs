import { createClient } from '@supabase/supabase-js';
import dotenv from 'dotenv';
dotenv.config();
const sb = createClient(process.env.SUPABASE_URL, process.env.SUPABASE_SERVICE_ROLE_KEY);
const vid = '50763b6a-1fad-4e1e-b2fc-296a1d66ebf9';
const { data: v } = await sb.from('ventures').select('id,name,current_lifecycle_stage,launch_mode,repo_url,deployment_url,deployment_target,is_scaffolding,build_model').eq('id',vid).single();
console.log('AltifyAI:', JSON.stringify(v,null,1));
const { data: leg, error: le } = await sb.from('venture_legal_overrides').select('*').eq('venture_id', vid);
console.log('venture_legal_overrides:', le ? 'ERR '+le.message : `rows=${leg.length}`, JSON.stringify(leg));
const { data: lt, error: lte } = await sb.from('legal_templates').select('*').limit(10);
console.log('legal_templates:', lte ? 'ERR '+lte.message : (lt||[]).map(r=>`${r.id}:${r.template_type}`).join(', '));
const { data: arts } = await sb.from('venture_artifacts').select('artifact_type,lifecycle_stage').eq('venture_id',vid).eq('is_current',true).order('lifecycle_stage');
const byStage={}; for(const a of (arts||[])) (byStage[a.lifecycle_stage] ||= []).push(a.artifact_type);
console.log('--- AltifyAI current artifacts by stage ---');
for (const k of Object.keys(byStage).sort((a,b)=>a-b)) console.log('  S'+k+': '+byStage[k].join(', '));
